DROP POLICY IF EXISTS "Ver mensajes internos propios o publicos" ON public.internal_messages;
CREATE POLICY "Ver mensajes internos propios o publicos"
ON public.internal_messages
FOR SELECT
USING (
  receiver_id IS NULL
  OR sender_id = auth.uid()
  OR receiver_id = auth.uid()
  OR EXISTS (
    SELECT 1
    FROM public.profiles p
    WHERE p.id = auth.uid()
      AND (p.role = 'admin' OR coalesce(p.is_helper, false) = true)
  )
);

