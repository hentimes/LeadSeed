-- 7. Función RPC para calcular disponibilidad (Endpoint ultrarrápido)
-- Esta función genera bloques de 1 hora (45m reunión + 15m descanso)
CREATE OR REPLACE FUNCTION get_available_slots(p_user_id UUID, p_start_date DATE, p_days INTEGER)
RETURNS TABLE (
    slot_date DATE,
    starts_at TIMESTAMP WITH TIME ZONE,
    disabled BOOLEAN
) AS $$
DECLARE
    current_date_iter DATE := p_start_date;
    end_date DATE := p_start_date + p_days - 1;
    v_day_of_week INTEGER;
    v_start_time TIME;
    v_end_time TIME;
    v_is_off BOOLEAN;
    v_current_slot TIMESTAMP WITH TIME ZONE;
    v_slot_end TIMESTAMP WITH TIME ZONE;
    v_conflict_count INTEGER;
BEGIN
    WHILE current_date_iter <= end_date LOOP
        -- Verificar si hay una excepción/bloqueo para esta fecha
        SELECT is_off_day, start_time, end_time INTO v_is_off, v_start_time, v_end_time
        FROM public.user_availability_overrides
        WHERE user_id = p_user_id AND specific_date = current_date_iter;

        IF NOT FOUND THEN
            -- Si no hay excepción, buscar el horario base semanal
            v_day_of_week := EXTRACT(DOW FROM current_date_iter);
            SELECT start_time, end_time INTO v_start_time, v_end_time
            FROM public.user_availability
            WHERE user_id = p_user_id AND day_of_week = v_day_of_week AND is_active = true;
            
            v_is_off := NOT FOUND;
        END IF;

        IF NOT v_is_off THEN
            -- Generar bloques de 1 hora dentro de la ventana de disponibilidad
            v_current_slot := current_date_iter + v_start_time;
            
            WHILE (v_current_slot + interval '1 hour')::time <= v_end_time LOOP
                v_slot_end := v_current_slot + interval '45 minutes';
                
                -- Chequear si ya hay una cita (appointment) que se superpone con este bloque
                SELECT count(*) INTO v_conflict_count
                FROM public.appointments
                WHERE user_id = p_user_id 
                AND status = 'agendada'
                AND start_time < (v_current_slot + interval '1 hour')
                AND end_time > v_current_slot;

                RETURN QUERY SELECT 
                    current_date_iter, 
                    v_current_slot, 
                    (v_conflict_count > 0) OR (v_current_slot < timezone('utc'::text, now()));
                
                v_current_slot := v_current_slot + interval '1 hour';
            END LOOP;
        END IF;

        current_date_iter := current_date_iter + 1;
    END LOOP;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;
