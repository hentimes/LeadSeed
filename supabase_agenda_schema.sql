-- 1. Tabla de Disponibilidad Semanal (Horario Base)
CREATE TABLE public.user_availability (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
    day_of_week INTEGER NOT NULL CHECK (day_of_week >= 0 AND day_of_week <= 6), -- 0=Domingo, 1=Lunes...
    start_time TIME NOT NULL, -- ej. '08:00'
    end_time TIME NOT NULL,   -- ej. '19:00'
    is_active BOOLEAN DEFAULT true,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
    UNIQUE(user_id, day_of_week)
);

-- 2. Tabla de Excepciones y Bloqueos de Disponibilidad
CREATE TABLE public.user_availability_overrides (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
    specific_date DATE NOT NULL,
    is_off_day BOOLEAN DEFAULT false, -- Si es true, todo el día está bloqueado (feriado, vacaciones)
    start_time TIME, -- Si is_off_day es false, define un horario especial para ese día específico
    end_time TIME,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
    UNIQUE(user_id, specific_date)
);

-- 3. Tabla de Citas (Appointments)
CREATE TABLE public.appointments (
    id UUID DEFAULT gen_random_uuid() PRIMARY KEY,
    user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
    lead_id UUID REFERENCES public.leads(id) ON DELETE CASCADE,
    start_time TIMESTAMP WITH TIME ZONE NOT NULL,
    end_time TIMESTAMP WITH TIME ZONE NOT NULL, -- Generalmente start_time + 45mins
    status TEXT NOT NULL DEFAULT 'agendada' CHECK (status IN ('agendada', 'cancelada', 'completada')),
    google_event_id TEXT,
    meet_link TEXT,
    notes TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 4. Habilitar Seguridad a Nivel de Fila (RLS)
ALTER TABLE public.user_availability ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.user_availability_overrides ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.appointments ENABLE ROW LEVEL SECURITY;

