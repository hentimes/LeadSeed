CREATE OR REPLACE FUNCTION public.get_available_slots(p_user_id uuid, p_start_date date, p_days integer)
RETURNS TABLE (
  slot_date date,
  starts_at timestamptz,
  disabled boolean
)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  current_date_iter date := p_start_date;
  end_date date := p_start_date + p_days - 1;
  v_day_of_week integer;
  v_start_time time;
  v_end_time time;
  v_is_off boolean;
  v_current_slot timestamptz;
  v_conflict_count integer;
BEGIN
  WHILE current_date_iter <= end_date LOOP
    SELECT is_off_day, start_time, end_time
    INTO v_is_off, v_start_time, v_end_time
    FROM public.user_availability_overrides
    WHERE user_id = p_user_id
      AND specific_date = current_date_iter;

    IF NOT FOUND THEN
      v_day_of_week := EXTRACT(DOW FROM current_date_iter);
      SELECT start_time, end_time
      INTO v_start_time, v_end_time
      FROM public.user_availability
      WHERE user_id = p_user_id
        AND day_of_week = v_day_of_week
        AND is_active = true;

      v_is_off := NOT FOUND;
    END IF;

    IF NOT v_is_off THEN
      v_current_slot := current_date_iter + v_start_time;

      WHILE (v_current_slot + interval '1 hour')::time <= v_end_time LOOP
        SELECT count(*) INTO v_conflict_count
        FROM public.appointments
        WHERE user_id = p_user_id
          AND status = 'agendada'
          AND start_time < (v_current_slot + interval '1 hour')
          AND end_time > v_current_slot;

        RETURN QUERY
        SELECT
          current_date_iter,
          v_current_slot,
          (v_conflict_count > 0) OR (v_current_slot < timezone('utc'::text, now()));

        v_current_slot := v_current_slot + interval '1 hour';
      END LOOP;
    END IF;

    current_date_iter := current_date_iter + 1;
  END LOOP;
END;
$$;
